"""Places the voice (take A, ElevenLabs voice "Mine") on the beat grid: each sentence group starts on a bar.
-> audio/vo.wav (film length) and vo.js (every word with its film time, for the picture)."""
import json, numpy as np, soundfile as sf, pathlib
D = pathlib.Path(__file__).parent
vo, sr = sf.read(D / 'vo/take-a.wav'); words = json.load(open(D / 'words-a.json'))
dur = sf.info(D / 'music.wav').duration
# [source start, source end, film time of the group's first word] ; first words land on downbeats of beats.json
DB = json.load(open(D.parent / 'beats.json'))['downbeats']
SEG = [(0.05, 6.15, DB[0]), (6.30, 9.90, DB[3]), (9.95, 13.82, DB[5]), (13.90, 17.50, DB[7]), (17.55, 21.20, DB[9]), (21.30, 25.60, DB[11] - 0.06), (25.80, 29.50, DB[14])]
out = np.zeros(int(dur * sr) + 1); placed = []
for s0, s1, at in SEG:
    first = next(w for w in words if w[1] >= s0)
    dst = at - (first[1] - s0)
    a, b = int(s0 * sr), int(s1 * sr); seg = vo[a:b].copy()
    f = int(0.012 * sr); seg[:f] *= np.linspace(0, 1, f); seg[-f:] *= np.linspace(1, 0, f)
    i = int(dst * sr); out[i:i + len(seg)] += seg
    placed += [[w[0], round(w[1] - s0 + dst, 3), round(w[2] - s0 + dst, 3)] for w in words if s0 <= w[1] < s1]
sf.write(D / 'vo.wav', out, sr)
(D.parent / 'vo.js').write_text('// generated by audio/place.py: [word, start s, end s] in film time\nexport const WORDS = ' + json.dumps(placed) + ';\n')
print(len(placed), 'words placed; last ends', placed[-1][2], 's of', round(dur, 2))
