"""Place the voice-over takes on the beat grid: each line's first word lands on a beat.
   uv run promo/audio/place.py     -> promo/audio/vo.wav, promo/vo.js, film.json duration"""
import json, subprocess, sys
from pathlib import Path
import numpy as np, soundfile as sf

F = Path(__file__).resolve().parents[1]; SR = 48000
SCRIPT = [
 ("l01a", "Three times a day, the same question. What should I eat now?", 0.0),
 ("l02a", "A diet chart answers it once. Then your day happens. Breakfast gets skipped. Lunch is at a wedding. Dinner is at ten.", 0.45),
 ("l03a", "Next Plate answers it fresh, every meal. It is a dietitian in your pocket that knows how your day is actually going.", 0.75),
 ("l04a", "So you don't have to decide. You get one clear plate. Real food, in real amounts, and the reason it is right for you today.", 0.5),
 ("l05a", "Ate something else? Just tell it. It doesn't scold you. It counts the meal, and quietly adjusts the rest of your day.", 0.55),
 ("l06c", "Eating out anyway? It shows you the two or three moves that make even chole bhature fit.", 0.55),
 ("l07a", "It remembers your week, so dinner isn't rajma again.", 0.45),
 ("l08a", "Your numbers are not copied from a chart. They are worked out from your age, your body and your goal. And it shows you how.", 0.55),
 ("l09a", "And it is careful. With diabetes, the grain stays on your plate. If something needs your doctor, it says so, and steps back.", 0.55),
 ("l10a", "No guesswork. No guilt. Just your next plate, decided.", 0.75),
 ("l11a", "Next Plate. Message me for your link.", 0.6),
]
grid = json.loads((F / "beats.json").read_text()); P, OFF = grid["period"], grid["offset"]
words_all = json.loads((F / "audio/vo/words.json").read_text())

def load(k):
    raw = subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-i", str(F / f"audio/vo/{k}.mp3"), "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True).stdout
    return np.frombuffer(raw, dtype=np.float32).copy()

def bounds(a):
    w = int(SR * 0.01); n = len(a) // w; rms = np.sqrt((a[: n * w].reshape(n, w) ** 2).mean(1) + 1e-12)
    thr = rms.max() * 10 ** (-38 / 20); idx = np.where(rms > thr)[0]
    return max(0, idx[0] * w - int(0.02 * SR)), min(len(a), (idx[-1] + 1) * w + int(0.12 * SR))

out, t_prev_end, FIRST_BEAT = [], 0.0, 2
placed = []
for i, (k, text, gap) in enumerate(SCRIPT):
    a = load(k); s, e = bounds(a); seg = a[s:e]; dur = len(seg) / SR
    earliest = (OFF + FIRST_BEAT * P) if i == 0 else t_prev_end + gap
    beat = int(np.ceil((earliest - OFF) / P - 1e-6)); t0 = OFF + beat * P
    # word timings: whisper's times for this take, shifted onto the film's clock; fall back to an even spread
    disp = text.split(); ww = words_all.get(k, [])
    if len(ww) == len(disp): wt = [[d, round((t0 + x[1] - s / SR - OFF) / P, 3), round((t0 + x[2] - s / SR - OFF) / P, 3)] for d, x in zip(disp, ww)]
    else:
        tot = sum(len(d) + 1 for d in disp); acc = 0; wt = []
        for d in disp: a0 = acc / tot; acc += len(d) + 1; wt.append([d, round((t0 + a0 * dur - OFF) / P, 3), round((t0 + acc / tot * dur - OFF) / P, 3)])
    placed.append((seg, t0)); t_prev_end = t0 + dur - 0.12
    out.append({"i": i + 1, "take": k, "text": text, "u": beat, "t0": round(t0, 3), "t1": round(t0 + dur - 0.12, 3), "u1": round((t0 + dur - 0.12 - OFF) / P, 3), "words": wt, "aligned": len(ww) == len(disp)})
    print(f"L{i+1:02d} {k} beat {beat:3d}  {t0:6.2f}-{t0+dur-0.12:6.2f}s  ({dur:4.2f}s){'' if len(ww)==len(disp) else '  [even spread]'}")
bar = 4 * P; total = np.ceil((t_prev_end + 2.6) / bar) * bar
mix = np.zeros(int(total * SR) + SR, dtype=np.float32)
for seg, t0 in placed:
    n0 = int(t0 * SR); f = int(0.008 * SR); seg = seg.copy(); seg[:f] *= np.linspace(0, 1, f); seg[-f:] *= np.linspace(1, 0, f); mix[n0:n0 + len(seg)] += seg
mix = mix[: int(total * SR)]; mix *= 0.89 / max(1e-6, np.abs(mix).max())
sf.write(F / "audio/vo.wav", np.stack([mix, mix], 1), SR, subtype="PCM_24")
(F / "vo.js").write_text("// generated by audio/place.py: the voice-over on the beat grid (u = beats)\nexport const VO = " + json.dumps(out, indent=1) + ";\nexport const DURATION = " + str(round(float(total), 3)) + ";\n")
cfg = json.loads((F / "film.json").read_text()); cfg["duration"] = round(float(total), 3); cfg["poster"] = round(out[9]["t1"] - 0.3, 2); (F / "film.json").write_text(json.dumps(cfg, indent=1))
print(f"film duration {total:.3f}s = {total/P:.0f} beats; end card from beat {out[10]['u']}")
