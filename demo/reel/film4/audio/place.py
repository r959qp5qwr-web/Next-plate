"""The calm take (ElevenLabs voice "Mine", take A) cut to its best reading of each line and placed on the film's clock.
-> audio/vo.wav and vo.js ([word, start, end] in film seconds)."""
import json, sys, numpy as np, soundfile as sf, pathlib
D = pathlib.Path(__file__).parent
vo, sr = sf.read(D / 'vo/calm-a.wav'); words = json.load(open(D / 'words-calm-a.json'))
dur = float(sys.argv[1]) if len(sys.argv) > 1 else 60
# [source start, source end, film time of the first word]
SEG = json.load(open(D / 'segments.json'))
out = np.zeros(int(dur * sr) + 1); placed = []
for s0, s1, at in SEG:
    first = next(w for w in words if w[1] >= s0); dst = at - (first[1] - s0)
    a, b = int(s0 * sr), int(s1 * sr); seg = vo[a:b].copy(); f = int(0.02 * sr)
    seg[:f] *= np.linspace(0, 1, f); seg[-f:] *= np.linspace(1, 0, f)
    i = int(dst * sr); n = min(len(seg), len(out) - i)
    if n > 0: out[i:i + n] += seg[:n]
    placed += [[w[0], round(w[1] - s0 + dst, 3), round(w[2] - s0 + dst, 3)] for w in words if s0 <= w[1] < s1]
sf.write(D / 'vo.wav', out, sr)
(D.parent / 'vo.js').write_text('// generated by audio/place.py\nexport const WORDS = ' + json.dumps(placed) + ';\n')
print(len(placed), 'words; last ends', placed[-1][2] if placed else None)
