"""Features film voice: take A cut into its seven lines at the measured quiet points between them (not at the transcript's word times,
which run about 0.15 s late and put cuts inside words), each line placed so its cut lands on its beat; then the 30 s film's own read of
"Next Plate. Made for you." (film4/audio/vo/end-a.mp3) on the end card.   uv run place.py <duration> -> vo.wav and ../vo.js"""
import json, sys, subprocess, numpy as np, soundfile as sf, pathlib
D = pathlib.Path(__file__).parent; dur = float(sys.argv[1]) if len(sys.argv) > 1 else 51
vo, sr = sf.read(D / 'vo/calm-a.wav'); words = json.load(open(D / 'words-calm-a.json'))
end = D / 'vo/end-a.wav'
if not end.exists(): subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(D.parent.parent / 'film4/audio/vo/end-a.mp3'), '-ar', str(sr), '-ac', '1', str(end)], check=True)
ea, _ = sf.read(end)
P = json.load(open(D / 'segments.json'))          # {"lines": [[cut in, cut out, film time of the cut in]], "end_at": film time the slogan clip starts}
out = np.zeros(int(dur * sr) + 1); placed = []
def put(seg, at, fade=0.04):
    seg = seg.copy(); f = int(fade * sr); seg[:f] *= np.linspace(0, 1, f); seg[-f:] *= np.linspace(1, 0, f)
    i = int(at * sr); n = min(len(seg), len(out) - i); out[i:i + n] += seg[:n]
for s0, s1, at in P['lines']:
    put(vo[int(s0 * sr):int(s1 * sr)], at)
    placed += [[w[0], round(w[1] - s0 + at, 3), round(w[2] - s0 + at, 3)] for w in words if s0 <= w[1] < s1]
put(ea, P['end_at'], 0.02)
placed += [['NextPlate.', P['end_at'] + 0.71, P['end_at'] + 1.73], ['Made', P['end_at'] + 2.12, P['end_at'] + 2.4], ['for', P['end_at'] + 2.45, P['end_at'] + 2.6], ['you.', P['end_at'] + 2.65, P['end_at'] + 3.06]]
sf.write(D / 'vo.wav', out, sr)
(D.parent / 'vo.js').write_text('// generated by audio/place.py\nexport const WORDS = ' + json.dumps(placed) + ';\n')
print(len(placed), 'words; last ends', placed[-1][2])
